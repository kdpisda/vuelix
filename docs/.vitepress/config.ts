import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, URL } from 'node:url'
import tailwindcss from '@tailwindcss/vite'
import { defineConfig } from 'vitepress'

interface CatalogItem { name: string, title: string, description: string, section: string, category: string, url: string }
interface ChangelogEntry { version: string, date: string, title: string, summary: string, items: string[] }

const SITE = 'https://vuelix.dev'
const readJson = <T>(rel: string): T => JSON.parse(readFileSync(fileURLToPath(new URL(rel, import.meta.url)), 'utf8'))
const changelog = readJson<ChangelogEntry[]>('../data/changelog.json')
const escapeXml = (s: string) => s.replace(/[<>&'"]/g, c => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '\'': '&apos;', '"': '&quot;' })[c]!)

// Generated by scripts/build-registry.mjs from registry/ui/*/meta.json (already sorted).
const catalog: CatalogItem[] = JSON.parse(
  readFileSync(fileURLToPath(new URL('../../registry/catalog.json', import.meta.url)), 'utf8'),
)

const SECTION_TITLES: Record<string, string> = {
  components: 'Components',
  blocks: 'Blocks',
  ai: 'AI',
  charts: 'Charts',
}

function sectionGroups(section: string) {
  const items = catalog.filter(c => c.section === section)
  const categories = [...new Set(items.map(c => c.category))]
  // A section with a single category shows as one flat group.
  if (categories.length <= 1)
    return [{ text: SECTION_TITLES[section]!, collapsed: false, items: items.map(c => ({ text: c.title, link: c.url })) }]
  return categories.map(category => ({
    text: section === 'components' ? category : `${SECTION_TITLES[section]} · ${category}`,
    collapsed: false,
    items: items.filter(c => c.category === category).map(c => ({ text: c.title, link: c.url })),
  }))
}

const gettingStarted = {
  text: 'Getting Started',
  items: [
    { text: 'Introduction', link: '/docs/' },
    { text: 'Installation', link: '/docs/installation' },
    { text: 'Theming', link: '/docs/theming' },
    { text: 'Motion Patterns', link: '/docs/motion' },
    { text: 'For AI Agents', link: '/docs/ai-agents' },
    { text: 'Changelog', link: '/changelog' },
  ],
}

const sidebar = [
  gettingStarted,
  ...Object.keys(SECTION_TITLES).flatMap(sectionGroups),
]

